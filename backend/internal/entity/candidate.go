package entity

// Candidate — лёгкий результат векторного поиска кандидатов (Top-K или по порогу).
// Это "сырая" находка pgvector: кто/что может быть совместимо по семантической близости.
// Полные данные о заявке/предмете при необходимости догружаются отдельно (avoid N+1).
type Candidate struct {
	// RequestID — заявка-владелец найденного "получаю" или сама найденная заявка
	// по направлению "отдаю". Ключ для дальнейшего бизнес-мэтчинга.
	RequestID int64
	// ItemID — предмет-кандидат (для направления "получаю" это чужой предмет,
	// который могут отдать; для "отдаю" — предмет-основание запроса).
	ItemID int64
	// OwnerID — пользователь-владелец предмета/заявки. Нужен, чтобы быстро
	// исключить собственные записи и проверять доступность в бизнес-слое.
	OwnerID string
	// Score — косинусное подобие в диапазоне [-1, 1], где 1 = идеальное совпадение.
	// Считается как 1 - (embedding <=> want) на стороне SQL.
	Score float64
}
