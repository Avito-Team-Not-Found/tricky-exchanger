// колонка в БД — VARCHAR(100), переполнение бэкенд не валидирует и отдаёт 500
export const CATEGORY_MAX_LENGTH = 100;

// требование SCRUM-52; записи, созданные до него, приходят с более коротким описанием, поэтому
// формы товара и заявки проверяют длину явно — antd не валидирует initialValues
export const DESCRIPTION_MIN_LENGTH = 50;

// категория с сервера может отсутствовать в справочнике (данные старше миграции): без своей
// опции редактирование молча сбросило бы значение, а вместе с ним и пул подбора
export function categoryOptions(current?: string): { value: string; label: string }[] {
  const options = ITEM_CATEGORIES.map((name) => ({ value: name, label: name }));
  if (current && !ITEM_CATEGORIES.some((name) => name === current)) {
    return [{ value: current, label: current }, ...options];
  }
  return options;
}
